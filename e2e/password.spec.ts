import { expect, test } from '@playwright/test'

test('settings sets and changes the password, and login accepts only the saved password', async ({
  page,
}) => {
  await page.goto('/settings')
  await page.getByLabel(/^Новый пароль/).fill('first-password')
  await page.getByLabel(/^Повторите новый пароль/).fill('different-password')
  await page.getByRole('button', { name: 'Задать пароль', exact: true }).click()
  await expect(page.getByText('Новые пароли не совпадают.', { exact: true })).toBeVisible()
  await page.getByLabel(/^Повторите новый пароль/).fill('first-password')
  await page.getByRole('button', { name: 'Задать пароль', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Смена пароля', exact: true })).toBeVisible()
  await expect(page.getByLabel(/^Новый пароль/)).toHaveValue('')
  await page.getByLabel(/^Текущий пароль/).fill('incorrect-password')
  await page.getByLabel(/^Новый пароль/).fill('second-password')
  await page.getByLabel(/^Повторите новый пароль/).fill('second-password')
  await page.getByRole('button', { name: 'Изменить пароль', exact: true }).click()
  await expect(page.getByText('Текущий пароль указан неверно.', { exact: true })).toBeVisible()
  await page.getByLabel(/^Текущий пароль/).fill('first-password')
  await page.getByRole('button', { name: 'Изменить пароль', exact: true }).click()
  await expect(page.getByLabel(/^Текущий пароль/)).toHaveValue('')
  await expect(page.getByLabel(/^Новый пароль/)).toHaveValue('')
  await expect(page.getByLabel(/^Повторите новый пароль/)).toHaveValue('')
  await page.getByRole('button', { name: 'Выйти', exact: true }).click()
  await page.getByRole('dialog').getByRole('button', { name: 'Выйти', exact: true }).click()
  await expect(page).toHaveURL(/\/login$/)
  await page.reload()
  await page.getByLabel(/^Электронная почта/).fill('alex@example.com')
  await page.getByLabel(/^Пароль/).fill('first-password')
  await page.getByRole('button', { name: 'Войти', exact: true }).click()
  await expect(
    page.getByText('Неверная электронная почта или пароль.', { exact: true }),
  ).toBeVisible()
  await page.getByLabel(/^Пароль/).fill('second-password')
  await page.getByRole('button', { name: 'Войти', exact: true }).click()
  await expect(page).toHaveURL('/')
})

test('registration stores a password that can be changed in settings', async ({ page }) => {
  await page.goto('/registration')
  await page.getByLabel(/^Ваше имя/).fill('Анна')
  await page.getByLabel(/^Электронная почта/).fill('anna@example.com')
  await page.getByLabel(/^Пароль/).fill('registered-password')
  await page.getByRole('checkbox').check()
  await page.getByRole('button', { name: 'Создать аккаунт', exact: true }).click()
  await expect(page).toHaveURL('/')
  await page.goto('/settings')
  await page.getByLabel(/^Текущий пароль/).fill('registered-password')
  await page.getByLabel(/^Новый пароль/).fill('changed-password')
  await page.getByLabel(/^Повторите новый пароль/).fill('changed-password')
  await page.getByRole('button', { name: 'Изменить пароль', exact: true }).click()
  await expect(page.getByLabel(/^Текущий пароль/)).toHaveValue('')
})
