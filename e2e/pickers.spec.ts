import { expect, test } from '@playwright/test'

for (const width of [1440, 375, 320]) {
  test(`custom calendar, clock and select work inside modals at ${width}px`, async ({ page }) => {
    await page.setViewportSize({ width, height: 900 })
    await page.goto('/ui-kit')
    const select = page.getByRole('combobox', { name: 'Направление', exact: true })
    await select.click()
    const popup = page.locator('[popover]:popover-open')
    await expect(popup.getByRole('button', { name: 'Италия', exact: true })).toBeFocused()
    await page.keyboard.press('End')
    await expect(popup.getByRole('button', { name: 'Португалия', exact: true })).toBeFocused()
    await page.keyboard.press('Enter')
    await expect(select).toHaveValue('portugal')
    await expect(popup).toHaveCount(0)
    await expect(select).toBeFocused()
    await select.press('ArrowDown')
    await expect(popup.getByRole('button', { name: 'Португалия', exact: true })).toBeFocused()
    await page.keyboard.press('Escape')
    await expect(popup).toHaveCount(0)
    const date = page.getByLabel('Дата в календаре', { exact: true })
    await date.click()
    const calendar = page.locator('[popover]:popover-open')
    await expect(calendar.locator('table')).toBeVisible()
    await expect(calendar.locator('button[value="2026-10-31"]')).toBeDisabled()
    await calendar.locator('button[value="2026-11-15"]').click()
    await expect(date).toHaveValue('15.11.2026')
    await date.press('Enter')
    await expect(calendar.locator('button[value="2026-11-15"]')).toBeFocused()
    await page.keyboard.press('ArrowRight')
    await expect(calendar.locator('button[value="2026-11-16"]')).toBeFocused()
    await page.keyboard.press('Enter')
    await expect(date).toHaveValue('16.11.2026')
    const time = page.getByLabel('Время в списке', { exact: true })
    await time.click()
    await expect(
      popup.getByRole('group', { name: 'Часы' }).getByRole('button', { name: '07', exact: true }),
    ).toBeDisabled()
    await popup
      .getByRole('group', { name: 'Часы' })
      .getByRole('button', { name: '14', exact: true })
      .click()
    await popup
      .getByRole('group', { name: 'Минуты' })
      .getByRole('button', { name: '45', exact: true })
      .click()
    await popup.getByRole('button', { name: 'Готово', exact: true }).click()
    await expect(time).toHaveValue('14:45')
  })

  test(`calendar, clock and select remain usable above modals at ${width}px`, async ({ page }) => {
    await page.setViewportSize({ width, height: 900 })
    await page.goto('/ui-kit')
    const popup = page.locator('[popover]:popover-open')
    await page.getByRole('button', { name: 'TripForm — новая поездка', exact: true }).click()
    const dialog = page.getByRole('dialog')
    const start = dialog.getByLabel('Начало поездки')
    await start.fill('2026-11-12')
    await start.click()
    await expect(popup.locator('table')).toBeVisible()
    const bounds = (await popup.boundingBox())!
    expect(bounds.x).toBeGreaterThanOrEqual(0)
    expect(bounds.x + bounds.width).toBeLessThanOrEqual(width)
    expect(bounds.y).toBeGreaterThanOrEqual(0)
    expect(bounds.y + bounds.height).toBeLessThanOrEqual(900)
    await popup.locator('button[value="2026-11-14"]').click()
    await expect(start).toHaveValue('14.11.2026')
    await start.click()
    await page.keyboard.press('Escape')
    await expect(popup).toHaveCount(0)
    await expect(dialog).toBeVisible()
    await page.keyboard.press('Escape')
    await expect(dialog).toHaveCount(0)
    await page.getByRole('button', { name: 'EventForm — событие', exact: true }).click()
    const eventStart = dialog.getByLabel(/^Начало/)
    await eventStart.click()
    await popup
      .getByRole('group', { name: 'Часы' })
      .getByRole('button', { name: '16', exact: true })
      .click()
    await popup
      .getByRole('group', { name: 'Минуты' })
      .getByRole('button', { name: '20', exact: true })
      .click()
    await popup.getByRole('button', { name: 'Готово', exact: true }).click()
    await expect(eventStart).toHaveValue('16:20')
    await dialog.getByRole('combobox', { name: 'Сохранённое место', exact: true }).click()
    await popup.getByRole('button', { name: 'Без привязки к месту', exact: true }).click()
    await expect(popup).toHaveCount(0)
    await expect(dialog).toBeVisible()
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  })
}
